import React from 'react';
import type { SimulatorMode } from '../../store/useAppStore';

const MODES: Record<SimulatorMode, { label: string; hint: string; tone: string; dot: string } | null> = {
  unknown: null,
  live: {
    label: 'Live LLM',
    hint: 'Replies are generated by the configured language model.',
    tone: 'bg-emerald-500/10 text-emerald-400 border-emerald-500/25',
    dot: 'bg-emerald-400',
  },
  offline: {
    label: 'Offline demo mode',
    hint: 'No LLM API key is configured on the backend. Replies come from a scripted keyword matcher, so only the built-in demo scenarios work.',
    tone: 'bg-amber-500/10 text-amber-400 border-amber-500/25',
    dot: 'bg-amber-400',
  },
  fallback: {
    label: 'LLM unavailable - scripted replies',
    hint: 'The backend could not reach the language model, so it answered with scripted keyword replies. Check the backend logs and LLM settings.',
    tone: 'bg-red-500/10 text-red-400 border-red-500/25',
    dot: 'bg-red-400',
  },
  unreachable: {
    label: 'Backend unreachable - static replies',
    hint: 'The API request failed, so the page showed a static canned reply.',
    tone: 'bg-red-500/10 text-red-400 border-red-500/25',
    dot: 'bg-red-400',
  },
};

export const SimulatorModeBadge: React.FC<{ mode: SimulatorMode }> = ({ mode }) => {
  const info = MODES[mode];
  if (!info) return null;
  return (
    <span
      title={info.hint}
      className={`inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full text-[9px] font-mono font-medium border ${info.tone}`}
    >
      <span className={`w-1.5 h-1.5 rounded-full ${info.dot}`}></span>
      {info.label}
    </span>
  );
};
